// ============================================================================
// 文件：include/cli/exit_code.h
// 作用：定义 CLI 的进程退出码枚举 ExitCode（guideline §5.1 / A-0.5）。
//       退出码是 CLI 与外界（脚本、集成测试、调用方）约定的唯一「结果信道」，
//       故集中于此单一定义点，避免各命令各写魔数。
// 分块依据：本文件只承载「退出码」这一横切概念，不涉及错误文本（见 cli_error.h）
//       或参数解析（见 arg_parser.h）。数值严格对齐 guideline §5.1 表格。
// ============================================================================
#pragma once

namespace idc::cli {

// ---------------------------------------------------------------------------
// ExitCode：进程退出码（guideline §5.1）。
// 数值即约定，不可随意调整——脚本与集成测试据此判定结果。
// ---------------------------------------------------------------------------
enum class ExitCode {
    Ok = 0,            // 成功：命令正常完成。
    ArgError = 1,      // 参数错误：缺必填、格式非法、互斥参数同时出现（§5.3 前 5 步）。
    RuntimeError = 2,  // 运行时错误：Core 业务错误，如坍缩不可行、保留区为空。
    InputError = 3,    // 输入文件错误：输入图像不存在、无法读取、格式不支持。
    OutputError = 4,   // 输出失败：输出目录不可创建、文件被占用、磁盘满。
    InternalError = 5, // 内部错误：未预期异常，需上报 bug。
};

// 取退出码的整数值（供 main 返回）。
inline int toInt(const ExitCode code) { return static_cast<int>(code); }

} // namespace idc::cli
