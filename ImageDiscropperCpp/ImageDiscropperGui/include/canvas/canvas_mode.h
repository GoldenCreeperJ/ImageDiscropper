// ============================================================================
// 文件：canvas/canvas_mode.h
// 作用：画布四态互斥交互模式枚举（计划 Phase 4「四态互斥模式」）。
//       把原先挤在「非绘制态」、仅靠「有无抓取者」隐式区分的三类左键手势（框选 / 标注选取 /
//       图片图层拾取）与「标注创建」显式拆成四个互斥单选态：任一时刻只处一态，进入一态即
//       取消前态选中（切走标注态清标注选中、切走/进入图片态在「选中图片」与「选中画布」间来回）。
// 分块依据：单独成头，令 CanvasView（存储 + 路由门控）、CanvasScene（图元可交互性）、
//           ToolPanel（模式按钮）、MainWindow（模式落地）共享同一枚举而不产生循环包含。
// 说明：枚举顺序即「交互模式」面板按钮顺序；值不入库、不入序列化，纯 GUI 交互态。
// ============================================================================
#pragma once

namespace idc::gui {

// ---------------------------------------------------------------------------
// CanvasMode：画布四态互斥交互模式。
// ---------------------------------------------------------------------------
enum class CanvasMode {
    Marquee,     // 框选：仅橡皮筋选区 + 选区框拖拽；标注 / 图片落位框不可交互（禁拾取）。
    ImagePick,   // 图片拾取：仅图片图层落位框可抓取拖拽；禁框选、禁标注交互。
    AnnoSelect,  // 标注选取：仅标注图元可选中 / 拖拽 / 手柄变换；禁框选、禁图层拾取；点空白取消标注选中。
    AnnoCreate,  // 标注创建：左键绘制当前形状（子行选形状）；禁框选 / 拾取 / 既有标注拖拽。
};

} // namespace idc::gui
